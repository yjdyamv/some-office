//! The globals substream of a BIFF8 workbook, record by record.
//!
//! Every byte here was measured from a workbook Microsoft Excel 2016 wrote;
//! `globals_reproduce_that_workbook_byte_for_byte` re-reads that workbook and
//! compares, so this file cannot silently drift (`docs/xls.md` §15.3).
//!
//! `XF`/`STYLE`/`FORMAT`/`FONT`/`SST`/`BOUNDSHEET` are *not* here: their
//! content depends on the workbook and `write.rs` builds them.

fn emit(out: &mut Vec<u8>, kind: u16, payload: &[u8]) {
    out.extend_from_slice(&kind.to_le_bytes());
    out.extend_from_slice(&(payload.len() as u16).to_le_bytes());
    out.extend_from_slice(payload);
}

