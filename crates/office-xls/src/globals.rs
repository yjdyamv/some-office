/// Appends the fixed part of the globals substream.
pub fn write_globals(out: &mut Vec<u8>) {
    for (kind, payload) in RECORDS {
        emit(out, *kind, payload);
    }
}

/// Always write this last: it closes the globals substream.
pub fn write_eof(out: &mut Vec<u8>) {
    emit(out, 0x000A, &[]);
}

#[cfg(test)]
mod tests {
    /// The workbook Excel wrote, kept as a *fixture only*: the writer no longer
    /// reads it (`docs/xls.md` §15.3).
    const REFERENCE: &[u8] = include_bytes!("../templates/globals.bin");

    /// Records whose payload depends on the workbook, so `write.rs` builds them.
    fn built_elsewhere(kind: u16) -> bool {
        matches!(kind, 0x0031 | 0x041E | 0x00E0 | 0x0293 | 0x087D)
    }

    #[test]
    fn globals_reproduce_that_workbook_byte_for_byte() {
        let mut expected = Vec::new();
        let mut at = 0usize;
        while at + 4 <= REFERENCE.len() {
            let kind = u16::from_le_bytes([REFERENCE[at], REFERENCE[at + 1]]);
            let len = u16::from_le_bytes([REFERENCE[at + 2], REFERENCE[at + 3]]) as usize;
            if kind == 0x000A {
                break;
            }
            if !built_elsewhere(kind) {
                expected.extend_from_slice(&REFERENCE[at..at + 4 + len]);
            }
            at += 4 + len;
        }
        let mut ours = Vec::new();
        super::write_globals(&mut ours);
        assert_eq!(ours.len(), expected.len(), "length differs");
        assert!(ours == expected, "content differs");
    }
}
