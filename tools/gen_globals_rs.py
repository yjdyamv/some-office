import sys
d = open("crates/office-xls/templates/globals.bin", "rb").read()
p, recs = 0, []
while p + 4 <= len(d):
    rid = int.from_bytes(d[p:p+2], "little"); ln = int.from_bytes(d[p+2:p+4], "little")
    if p + 4 + ln > len(d): break
    recs.append((rid, d[p+4:p+4+ln])); p += 4 + ln
from collections import Counter
c = Counter(r for r, _ in recs)
NAMES = {0x0809:"bof",0x00E1:"interface_hdr",0x00C1:"mms",0x00E2:"interface_end",0x005C:"write_access",
 0x0042:"codepage",0x0161:"dsf",0x01C0:"excel9_file",0x013D:"tab_id",0x009C:"builtin_fmt_cnt",
 0x0019:"window_protect",0x0012:"protect",0x0013:"password",0x01AF:"protect_rev4",0x01BC:"protection_rev4",
 0x003D:"window1",0x0040:"backup",0x008D:"hide_obj",0x0022:"date_mode",0x000E:"precision",
 0x01B7:"refresh_all",0x00DA:"book_bool",0x087C:"feat_hdr",0x088E:"feat",0x0160:"use_selfs",
 0x089A:"feat11",0x08A3:"feat12",0x008C:"country",0x01C1:"excel9_names",0x0863:"book_ext",
 0x0896:"roundtrip",0x089B:"theme12",0x088C:"theme",0x000A:"eof"}
out = []
w = out.append
w('//! The globals substream every BIFF8 workbook starts with.\n//!')
w('//! Generated by `tools/gen_globals_rs.py` from a workbook written by')
w('//! Microsoft Excel 2016, then checked byte for byte against that file by')
w('//! `globals_match_the_reference` — see `docs/xls.md` §15.\n//!')
w('//! Excel rejects a workbook that is missing *any* of these records, so the')
w('//! list is not a "minimal" one: it is what Excel itself emits for a new')
w('//! workbook. The formula-like parts (styles, formats, number formats) are')
w('//! built by loops below; the rest are literal payloads.\n')
w('use super::write::push_record;\n')
# formulaic groups
xfs = [(rid, v) for rid, v in recs if rid == 0x00E0]
pairs = [(int.from_bytes(v[0:2], "little"), int.from_bytes(v[2:4], "little")) for _, v in xfs]
w('/// `(ifnt, ifmt)` of the 62 cell formats, in order.\nconst XF_PAIRS: [(u16, u16); %d] = [' % len(pairs))
for i in range(0, len(pairs), 6):
    w("    " + " ".join("(%d, %d)," % p for p in pairs[i:i+6]))
w('];\n')
w('const XF_HEAD: [u8; 4] = [0xf5, 0xff, 0x10, 0x00];')
w('const XF_TAIL: [u8; 12] = [0x00, 0xf4, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xc0, 0x20];\n')
w('/// One `XF` record (22 byte payload).\npub fn xf(ifnt: u16, ifmt: u16) -> Vec<u8> {')
w('    let mut v = Vec::with_capacity(22);')
w('    v.extend_from_slice(&ifnt.to_le_bytes());')
w('    v.extend_from_slice(&ifmt.to_le_bytes());')
w('    v.extend_from_slice(&XF_HEAD);')
w('    v.extend_from_slice(&XF_TAIL);\n    v\n}\n')
xfext = [(rid, v) for rid, v in recs if rid == 0x087D]
tpl = xfext[0][1]
w('/// One `XFEXT` record: the body of the first one with its XF index patched.\n')
w('const XFEXT_TEMPLATE: [u8; %d] = [' % len(tpl))
for i in range(0, len(tpl), 12):
    w("    " + " ".join("0x%02x," % b for b in tpl[i:i+12]))
w('];\n')
w('pub fn xfext(index: u16, out: &mut Vec<u8>) {')
w('    let mut v = XFEXT_TEMPLATE.to_vec();')
w('    v[8..10].copy_from_slice(&index.to_le_bytes());')
w('    push_record(out, 0x087D, &v);\n}\n')
w('/// `STYLE` uses a localised name, so the index is the only variable part.\npub fn style(istd: u16, name: &str, out: &mut Vec<u8>) {')
w('    let mut v = Vec::new();')
w('    v.extend_from_slice(&istd.to_le_bytes());')
w('    v.push(name.chars().count() as u8);')
w('    v.push(0);')
w('    for u in name.encode_utf16() { v.extend_from_slice(&u.to_le_bytes()); }')
w('    push_record(out, 0x0293, &v);\n}\n')
w('/// The 47 built-in style names Excel ships, e.g. `常规 1`.\npub fn style_names() -> Vec<String> {')
w('    (1..=47).map(|n| format!("常规 {n}")).collect()\n}\n')
# literal payloads
order = [0x0809,0x00E1,0x00C1,0x00E2,0x005C,0x0042,0x0161,0x01C0,0x013D,0x009C,0x0019,0x0012,0x0013,0x01AF,0x01BC,
         0x00E0,0x087D,0x0293,0x003D,0x0040,0x008D,0x0022,0x000E,0x01B7,0x00DA,0x087C,0x088E,0x0160,0x089A,0x08A3,
         0x008C,0x01C1,0x0863,0x0896,0x089B,0x088C,0x000A]
lit = {}
for rid, v in recs:
    if c[rid] == 1 and rid not in (0x00E0, 0x087D, 0x0293):
        lit.setdefault(rid, v)
for rid in sorted(lit):
    nm = NAMES.get(rid, "record_%04x" % rid).upper()
    v = lit[rid]
    w('/// `0x%04X` — %d bytes.\nconst %s: [u8; %d] = [' % (rid, len(v), nm, len(v)))
    for i in range(0, len(v), 12):
        w("    " + " ".join("0x%02x," % b for b in v[i:i+12]))
    w('];\n')
w('/// Appends the whole globals substream up to and including its `EOF`.\npub fn write_globals(out: &mut Vec<u8>) {')
for rid in order:
    if rid in lit:
        nm = NAMES.get(rid, "record_%04x" % rid).upper()
        w('    push_record(out, 0x%04X, &%s);' % (rid, nm))
    elif rid == 0x00E0:
        w('    for (ifnt, ifmt) in XF_PAIRS {')
        w('        let xf = xf(ifnt, ifmt);')
        w('        push_record(out, 0x00E0, &xf);')
        w('    }')
    elif rid == 0x087D:
        w('    for i in 0..XF_PAIRS.len() as u16 { xfext(i, out); }')
    elif rid == 0x0293:
        w('    for (i, name) in style_names().iter().enumerate() {')
        w('        style(16 + i as u16, name, out);')
        w('    }')
w('}')
open("crates/office-xls/src/globals.rs", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote globals.rs, %d lines, %d literal records" % (len(out), len(lit)))
